def _verify():
    """Our bisplev against scipy's, over every fit, if scipy is here."""
    try:
        from scipy.interpolate import bisplev as ref
    except ImportError:
        print("scipy is not installed - nothing to verify against.")
        print("pip install scipy, then run this again.")
        return 1
    bad = 0
    for name, tck in FITS.items():
        x0, x1, y0, y1 = domain(tck)
        worst, at = 0.0, None
        for i in range(41):
            for j in range(41):
                x = x0 + (x1 - x0) * i / 40.0
                y = y0 + (y1 - y0) * j / 40.0
                a, b = bisplev(x, y, tck), float(ref(x, y, tck))
                e = abs(a - b) / max(abs(b), 1e-12)
                if e > worst:
                    worst, at = e, (x, y, a, b)
        ok = worst < 1e-12
        bad += 0 if ok else 1
        print("%-14s %4d x %4d pts   worst relative error %.2e   %s"
              % (name, 41, 41, worst, "ok" if ok else "MISMATCH at %r" % (at,)))

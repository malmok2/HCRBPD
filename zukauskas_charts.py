"""Zukauskas' pressure-drop charts for cross flow over a tube bank.

WHAT THIS IS
------------
Zukauskas (1972) gives the bundle pressure drop as

    dp = N_L * chi * f * (rho * u_max^2 / 2)

with the friction factor `f` and the pitch correction `chi` read off four
charts - two for the in-line bank and two for the staggered one.  They are
CHARTS: there is no closed form to transcribe, which is why this correlation
is usually quoted as "read from the figure".

    in-line     f   vs Re_max, one curve per X_L       chi vs (X_T-1)/(X_L-1)
    staggered   f   vs Re_max, one curve per X_T       chi vs X_T/X_L

PROVENANCE - read this before trusting a number out of it
---------------------------------------------------------
The four bicubic B-spline fits below are NOT ours and were NOT written from
memory.  They are the digitisations published in the `ht` library
(Chemical Engineering Design Library), MIT licensed, copied verbatim:

    ht 1.2.0, ht/conv_tube_bank.py - dP_inline_f_tck, dP_inline_correction_tck,
    dP_staggered_f_tck, dP_staggered_correction_tck
    https://github.com/CalebBell/ht     (licence in third_party/ht-LICENSE.txt)

which are in turn digitisations of

    A. Zukauskas, "Heat transfer from tubes in crossflow", in Advances in Heat
    Transfer, vol. 8, pp. 93-160, Academic Press, 1972; as reprinted in
    T. L. Bergman, A. S. Lavine, F. P. Incropera and D. P. DeWitt,
    "Introduction to Heat Transfer", 6th ed., Wiley, 2011, figs. 7.14 / 7.15.

So the chain is chart -> digitiser -> spline, and the last step cannot be more
accurate than the first.  `ht`'s own note on these fits says the smoothing was
tuned to the limit of what the digitised points support.  Treat the result as
a chart reading, not as a formula.

ONE DELIBERATE DEPARTURE FROM `ht`
----------------------------------
`ht.dP_Zukauskas` picks the chart by testing `S_T == S_L`: equal pitches take
the in-line charts, unequal ones the staggered charts.  That is a shortcut,
and for this study it is the wrong one - a STAGGERED bank on a square pitch
would be read off the IN-LINE chart, and an IN-LINE bank on a rectangular
pitch off the STAGGERED one.  Here the arrangement is passed in and picks the
chart, which is what the figures themselves say.  Everything else - the knots,
the coefficients, the meaning of each axis - is `ht`'s.

The charts are only drawn over a finite range.  Outside it a spline does not
extrapolate a chart, it invents one, so `friction()` clamps to the fitted
domain and says that it did rather than handing back a number that looks fine.
"""


def _span(t, k, x):
    """The knot span containing x, held inside [k, n-1]."""
    n = len(t) - k - 1
    if x <= t[k]:
        return k
    if x >= t[n]:
        return n - 1
    lo, hi = k, n
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if x < t[mid]:
            hi = mid
        else:
            lo = mid
    return lo


def _basis(t, k, x):
    """Cox-de Boor: the k+1 non-zero B-spline basis values at x.

    Returns (i, vals), vals[j] belonging to basis function i-k+j.
    """
    i = _span(t, k, x)
    vals = [0.0] * (k + 1)
    vals[0] = 1.0
    left = [0.0] * (k + 1)
    right = [0.0] * (k + 1)
    for j in range(1, k + 1):
        left[j] = x - t[i + 1 - j]
        right[j] = t[i + j] - x
        saved = 0.0
        for r in range(j):
            denom = right[r + 1] + left[j - r]
            temp = vals[r] / denom if denom else 0.0
            vals[r] = saved + right[r + 1] * temp
            saved = left[j - r] * temp
        vals[j] = saved
    return i, vals


def bisplev(x, y, tck):
    """One point off a tensor-product spline, in plain Python.

    scipy's `bisplev` does this; scipy is not a dependency of this project and
    will not become one for four fixed tables, so the evaluation is written
    out.  Verified against scipy.interpolate.bisplev over every fit's domain -
    `python3 zukauskas_charts.py --verify` if scipy happens to be installed.
    """
    tx, ty, c, kx, ky = tck
    ny = len(ty) - ky - 1
    ix, bx = _basis(tx, kx, x)
    iy, by = _basis(ty, ky, y)
    total = 0.0
    for a in range(kx + 1):
        wa = bx[a]
        if wa == 0.0:
            continue
        row = (ix - kx + a) * ny
        acc = 0.0
        for b in range(ky + 1):
            acc += by[b] * c[row + iy - ky + b]
        total += wa * acc
    return total


def domain(tck):
    """(x_lo, x_hi, y_lo, y_hi) of one fit, read off its own knots."""
    tx, ty, c, kx, ky = tck
    return (tx[kx], tx[len(tx) - kx - 1], ty[ky], ty[len(ty) - ky - 1])


def _clamp(v, tck, axis):
    """Hold v inside the fitted range of one axis; say if it had to."""
    t, k = (tck[0], tck[3]) if axis == 0 else (tck[1], tck[4])
    lo, hi = t[k], t[len(t) - k - 1]
    if v < lo:
        return lo, (v, lo, hi)
    if v > hi:
        return hi, (v, lo, hi)
    return v, None


def friction(staggered, XT, XL, Re):
    """f and chi off the charts.

    XT = S_T/D, XL = S_L/D, Re on the maximum (gap) velocity.  Returns
    (f, chi, clamped), `clamped` naming every axis that had to be held inside
    the chart as (axis, asked, lo, hi).
    """
    clamped = []

    def hold(v, tck, axis, what):
        v2, note = _clamp(v, tck, axis)
        if note:
            clamped.append((what, note[0], note[1], note[2]))
        return v2

    if staggered:
        ftck, ctck = STAGGERED_F, STAGGERED_CHI
        f = bisplev(hold(Re, ftck, 0, "Re"), hold(XT, ftck, 1, "X_T"), ftck)
        par = XT / XL if XL else 1.0
        chi = bisplev(hold(par, ctck, 0, "X_T/X_L"), hold(Re, ctck, 1, "Re"), ctck)
    else:
        ftck, ctck = INLINE_F, INLINE_CHI
        f = bisplev(hold(Re, ftck, 0, "Re"), hold(XL, ftck, 1, "X_L"), ftck)
        par = (XT - 1.0) / (XL - 1.0) if XL != 1.0 else 1.0
        chi = bisplev(hold(par, ctck, 0, "(X_T-1)/(X_L-1)"),
                      hold(Re, ctck, 1, "Re"), ctck)
    return f, chi, clamped


